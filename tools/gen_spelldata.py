"""Generates SpellData.lua from the client's Spell.dbc (3.3.5a, build 12340).

The tables mirror how TrinityCore handles combat (src/server/game/Combat, Spells):
- NoInitialAggro: SPELL_ATTR1_NO_THREAT or SPELL_ATTR3_NO_INITIAL_AGGRO (SpellInfo::HasInitialAggro).
  Such a spell refreshes combat only on a target that is already in combat and never passes combat
  on to the caster of a helpful spell. Only spells of class skill lines (SkillLine category 7:
  class, pet and racial spells) are kept, plus the SpellMgr.cpp fixes.
- SuppressCombat: SPELL_EFFECT_SANCTUARY or SPELL_AURA_FEIGN_DEATH (Vanish, Feign Death, ...).
  The unit drops out of combat at once, but its opponents stay in combat with it.
- EndCombat: SPELL_AURA_MOD_UNATTACKABLE (Divine Intervention, Phase Shift, ...). Combat ends on
  both sides, like a death.

Usage: python tools/gen_spelldata.py <dbc folder> > SpellData.lua
"""
import struct
import sys

ATTR1_NO_THREAT = 0x00000400
ATTR3_NO_INITIAL_AGGRO = 0x00020000
EFFECT_SANCTUARY = 79
AURA_FEIGN_DEATH = 66
AURA_MOD_UNATTACKABLE = 93
# SpellMgr.cpp fixes in TrinityCore
NO_AGGRO_ADD = {50526, 15290, 17466, 17467}
NO_AGGRO_REMOVE = {72347}

# Spell.dbc field indices
F_ATTR_EX = 5
F_ATTR_EX3 = 7
F_EFFECT = slice(71, 74)
F_EFFECT_AURA = slice(95, 98)
F_NAME = 136


def load(folder, name):
    data = open(folder + '/' + name, 'rb').read()
    _, count, fields, size, _ = struct.unpack('<4s4I', data[:20])
    records = [struct.unpack('<%dI' % fields, data[20 + i * size:20 + (i + 1) * size]) for i in range(count)]
    strings = data[20 + count * size:]
    return records, lambda o: strings[o:strings.index(b'\0', o)].decode('utf-8', 'replace')


def write_table(name, comment, spells):
    print()
    print('-- ' + comment)
    print('CombatTracking.%s = {' % name)
    for spell_id in sorted(spells):
        print('\t[%d] = true, -- %s' % (spell_id, spells[spell_id]))
    print('}')


def main(folder):
    class_lines = {r[0] for r in load(folder, 'SkillLine.dbc')[0] if r[1] == 7}
    class_spells = {r[2] for r in load(folder, 'SkillLineAbility.dbc')[0] if r[1] in class_lines}
    spells, string = load(folder, 'Spell.dbc')
    no_aggro, suppress, end = {}, {}, {}
    for r in spells:
        spell_id, name = r[0], string(r[F_NAME])
        flagged = (r[F_ATTR_EX] & ATTR1_NO_THREAT) or (r[F_ATTR_EX3] & ATTR3_NO_INITIAL_AGGRO)
        if (spell_id in class_spells and flagged and spell_id not in NO_AGGRO_REMOVE) or spell_id in NO_AGGRO_ADD:
            no_aggro[spell_id] = name
        if EFFECT_SANCTUARY in r[F_EFFECT] or AURA_FEIGN_DEATH in r[F_EFFECT_AURA]:
            suppress[spell_id] = name
        if AURA_MOD_UNATTACKABLE in r[F_EFFECT_AURA]:
            end[spell_id] = name

    print('-- Generated by tools/gen_spelldata.py from Spell.dbc 3.3.5a (12340). Do not edit.')
    print('CombatTracking = CombatTracking or {}')
    write_table('NoInitialAggro', 'Spells that only refresh combat on a target already in combat.', no_aggro)
    write_table('SuppressCombat', 'The unit leaves combat at once; its opponents stay in combat with it.', suppress)
    write_table('EndCombat', 'Combat ends on both sides, like a death.', end)


main(sys.argv[1])
